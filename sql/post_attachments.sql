-- =====================================================
-- 글 첨부파일
--   · 파일: Storage 버킷 'post-files' (공개 읽기, 파일당 10MB, 허용 형식 제한)
--   · 목록: post_attachments 테이블 (글 삭제 시 함께 삭제)
--   · 업로드 흐름: 글 등록(create_post) → 방금 만든 글 폴더(<글id>/…)에 업로드 → add_post_attachments 로 등록
--   · 익명 업로드는 "10분 안에 만들어진 글"의 폴더에만 허용 (아무 데나 업로드 방지)
-- idempotent
-- =====================================================

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('post-files', 'post-files', true, 10485760, array[
    'image/png','image/jpeg','image/gif','image/webp','image/heic','image/heif',
    'application/pdf','text/plain',
    'application/zip','application/x-zip-compressed',
    'application/msword','application/vnd.openxmlformats-officedocument.wordprocessingml.document',
    'application/vnd.ms-excel','application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
    'application/vnd.ms-powerpoint','application/vnd.openxmlformats-officedocument.presentationml.presentation',
    'application/x-hwp','application/haansofthwp','application/vnd.hancom.hwp','application/vnd.hancom.hwpx'
])
on conflict (id) do update
    set public = excluded.public,
        file_size_limit = excluded.file_size_limit,
        allowed_mime_types = excluded.allowed_mime_types;

create table if not exists public.post_attachments (
    id         bigint generated by default as identity primary key,
    post_id    bigint not null references public.posts(id) on delete cascade,
    path       text   not null unique,
    name       text   not null,
    size       bigint not null default 0,
    mime       text,
    created_at timestamptz not null default now()
);
create index if not exists post_attachments_post_idx on public.post_attachments (post_id);

alter table public.post_attachments enable row level security;
drop policy if exists post_attachments_select on public.post_attachments;
create policy post_attachments_select on public.post_attachments for select
    using (exists (select 1 from public.posts p where p.id = post_id));
revoke all on public.post_attachments from anon, authenticated;
grant select on public.post_attachments to anon, authenticated;

-- Storage: 읽기는 공개 버킷이라 별도 정책 불필요. 업로드만 방금 만든 글의 폴더로 제한.
drop policy if exists post_files_insert on storage.objects;
create policy post_files_insert on storage.objects for insert to anon, authenticated
    with check (
        bucket_id = 'post-files'
        and (storage.foldername(name))[1] ~ '^[0-9]+$'
        and exists (
            select 1 from public.posts p
            where p.id = ((storage.foldername(name))[1])::bigint
              and p.created_at > now() - interval '10 minutes'
        )
    );

-- 첨부 등록 (글 비밀번호 확인, 글당 5개까지)
create or replace function public.add_post_attachments(p_post_id bigint, p_password text, p_files jsonb)
returns integer
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
    v_res text;
    f     jsonb;
    n     integer := 0;
    v_cnt integer;
begin
    if p_files is null or jsonb_typeof(p_files) <> 'array' or jsonb_array_length(p_files) = 0 then
        return 0;
    end if;
    if jsonb_array_length(p_files) > 5 then
        raise exception '파일은 최대 5개까지 첨부할 수 있어요.' using errcode = 'P0001';
    end if;

    v_res := public._verify_secret('post', p_post_id, p_password);
    if v_res <> 'ok' and not public.is_admin_user() then
        raise exception '비밀번호가 맞지 않아요.' using errcode = 'P0001';
    end if;

    select count(*) into v_cnt from public.post_attachments where post_id = p_post_id;
    if v_cnt + jsonb_array_length(p_files) > 5 then
        raise exception '파일은 글당 최대 5개까지 첨부할 수 있어요.' using errcode = 'P0001';
    end if;

    for f in select * from jsonb_array_elements(p_files) loop
        -- 해당 글 폴더 아래, 실제로 업로드된 파일만 등록
        if (f->>'path') !~ ('^' || p_post_id::text || '/[A-Za-z0-9._-]+$') then continue; end if;
        if not exists (select 1 from storage.objects o where o.bucket_id = 'post-files' and o.name = f->>'path') then continue; end if;
        insert into public.post_attachments (post_id, path, name, size, mime)
        values (p_post_id, f->>'path', left(coalesce(nullif(btrim(f->>'name'), ''), '파일'), 120),
                coalesce((f->>'size')::bigint, 0), left(f->>'mime', 100))
        on conflict (path) do nothing;
        n := n + 1;
    end loop;
    return n;
end;
$$;

grant execute on function public.add_post_attachments(bigint, text, jsonb) to anon, authenticated;
