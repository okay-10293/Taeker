-- =====================================================
-- 태커 달력 — 누구나 일정 추가 (비로그인, 닉네임 + 비밀번호)
--
-- ● 새 테이블/함수만 추가하므로 먼저 실행해도 기존 기능에 영향 없음
-- ● 일정 삭제는 등록할 때 정한 비밀번호로만 가능 (관리자는 비밀번호 없이 삭제 가능)
-- ● 비밀번호는 bcrypt 해시로만 저장되고 외부에서 조회할 수 없음 (post_secrets 와 같은 방식)
-- ● idempotent: 여러 번 실행해도 안전
-- 의존: sql/anonymous_mode.sql 의 _check_nick, _check_client, secret_fails, is_admin_user()
-- =====================================================

create table if not exists public.calendar_events (
    id         bigint generated by default as identity primary key,
    event_date date        not null,
    title      text        not null,
    memo       text,
    nickname   text        not null default '익명',
    client_id  text,
    created_at timestamptz not null default now()
);
create index if not exists calendar_events_date_idx on public.calendar_events (event_date);
create index if not exists calendar_events_client_idx on public.calendar_events (client_id, created_at);

create table if not exists public.calendar_secrets (
    event_id bigint primary key references public.calendar_events(id) on delete cascade,
    pw_hash  text not null
);

alter table public.calendar_events  enable row level security;
alter table public.calendar_secrets enable row level security;

-- 일정은 누구나 읽을 수 있지만 기기 식별값(client_id)은 공개하지 않는다.
drop policy if exists calendar_events_select_all on public.calendar_events;
create policy calendar_events_select_all on public.calendar_events for select using (true);

revoke all on public.calendar_events  from anon, authenticated;
revoke all on public.calendar_secrets from anon, authenticated;
grant select (id, event_date, title, memo, nickname, created_at)
    on public.calendar_events to anon, authenticated;

-- ---------- 일정 추가 ----------
create or replace function public.create_calendar_event(
    p_date date, p_title text, p_memo text,
    p_nickname text, p_password text, p_client_id text
)
returns bigint
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
    v_nick  text;
    v_admin boolean := public.is_admin_user();
    v_id    bigint;
begin
    perform public._check_client(p_client_id);
    v_nick := public._check_nick(p_nickname);

    if p_date is null
       or p_date < (current_date - interval '1 year')
       or p_date > (current_date + interval '2 years') then
        raise exception '날짜는 오늘 기준 1년 전 ~ 2년 후까지만 등록할 수 있어요.' using errcode = 'P0001';
    end if;
    if p_password is null or char_length(p_password) < 4 or char_length(p_password) > 30 then
        raise exception '비밀번호는 4~30자로 입력해주세요.' using errcode = 'P0001';
    end if;
    if char_length(btrim(coalesce(p_title, ''))) not between 1 and 40 then
        raise exception '일정 제목은 1~40자로 입력해주세요.' using errcode = 'P0001';
    end if;
    if char_length(coalesce(p_memo, '')) > 300 then
        raise exception '메모는 300자까지 입력할 수 있어요.' using errcode = 'P0001';
    end if;

    if not v_admin then
        if exists (
            select 1 from public.calendar_events
            where client_id = p_client_id and created_at > now() - interval '10 seconds'
        ) then
            raise exception '일정은 10초에 한 번만 등록할 수 있어요.' using errcode = 'P0001';
        end if;
        if (select count(*) from public.calendar_events
            where client_id = p_client_id and created_at > now() - interval '1 day') >= 20 then
            raise exception '하루에 등록할 수 있는 일정 수(20개)를 넘었어요.' using errcode = 'P0001';
        end if;
        if (select count(*) from public.calendar_events where event_date = p_date) >= 60 then
            raise exception '이 날짜에는 더 이상 일정을 등록할 수 없어요.' using errcode = 'P0001';
        end if;
    end if;

    insert into public.calendar_events (event_date, title, memo, nickname, client_id)
    values (p_date, btrim(p_title), nullif(btrim(coalesce(p_memo, '')), ''), v_nick, p_client_id)
    returning id into v_id;

    insert into public.calendar_secrets (event_id, pw_hash)
    values (v_id, extensions.crypt(p_password, extensions.gen_salt('bf')));

    return v_id;
end;
$$;

-- ---------- 비밀번호 확인 (오답 5회 → 10분 잠금, secret_fails 재사용) ----------
create or replace function public._verify_calendar_secret(p_id bigint, p_password text)
returns text
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
    v_hash text;
    v_fail public.secret_fails%rowtype;
begin
    select pw_hash into v_hash from public.calendar_secrets where event_id = p_id;
    if v_hash is null then return 'notfound'; end if;

    select * into v_fail from public.secret_fails where kind = 'calendar' and target_id = p_id;
    if v_fail.locked_until is not null and v_fail.locked_until > now() then
        return 'locked';
    end if;

    if extensions.crypt(coalesce(p_password, ''), v_hash) = v_hash then
        delete from public.secret_fails where kind = 'calendar' and target_id = p_id;
        return 'ok';
    end if;

    insert into public.secret_fails(kind, target_id, fails)
    values ('calendar', p_id, 1)
    on conflict (kind, target_id) do update
        set fails = case when public.secret_fails.locked_until is not null
                              and public.secret_fails.locked_until <= now()
                         then 1 else public.secret_fails.fails + 1 end,
            locked_until = null;

    update public.secret_fails
    set fails = 0, locked_until = now() + interval '10 minutes'
    where kind = 'calendar' and target_id = p_id and fails >= 5;

    return 'wrong';
end;
$$;

-- ---------- 일정 삭제 ----------
create or replace function public.delete_calendar_event(p_id bigint, p_password text)
returns text
language plpgsql
security definer
set search_path = public, extensions
as $$
declare v_res text;
begin
    v_res := public._verify_calendar_secret(p_id, p_password);
    if v_res = 'ok' or (public.is_admin_user() and exists (select 1 from public.calendar_events where id = p_id)) then
        delete from public.calendar_events where id = p_id;
        return 'ok';
    end if;
    return v_res;
end;
$$;

revoke all on function public._verify_calendar_secret(bigint, text) from public, anon, authenticated;
grant execute on function public.create_calendar_event(date, text, text, text, text, text) to anon, authenticated;
grant execute on function public.delete_calendar_event(bigint, text) to anon, authenticated;
